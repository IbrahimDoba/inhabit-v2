// Dev-only: turns every emoji the app uses into a Twemoji sticker icon.
//
// Usage: node scripts/build-icons.mjs
//
// Scans src/ for emoji, downloads each one's Twemoji SVG (cached in
// assets/icons/svg/), and renders a PNG with a thick white sticker outline
// into assets/icons/. Scene decorations listed in PLAIN also get an
// un-outlined copy (<code>-plain.png). Then writes src/constants/icons.ts, the
// lookup the <Icon> component uses. Run it again after adding a new emoji.
//
// Twemoji graphics: CC-BY 4.0, https://github.com/jdecked/twemoji (credited in Settings).

import { Resvg } from '@resvg/resvg-js';
import { existsSync } from 'node:fs';
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const SRC = 'src';
const OUT = 'assets/icons';
const SVG_CACHE = join(OUT, 'svg');
const TWEMOJI = 'https://cdn.jsdelivr.net/gh/jdecked/twemoji@latest/assets/svg';
/** Rendered size in pixels: crisp at 3x up to about 50 points. */
const SIZE = 160;
/** Outline thickness and padding, in Twemoji's 36-unit artboard. */
const OUTLINE = 2.3;
const PAD = 3.2;
/** Drawn into the scene itself, where a sticker outline would look stuck on. */
const PLAIN = ['🌿', '🌼', '🍄', '🌱', '🌸', '🌾', '🦋'];
/** Text marks, not pictures. */
const SKIP = new Set(['✓', '✔']);

const EMOJI = /(?:[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}\u{2B50}\u{2B06}\u{23F0}-\u{23FF}\u{2194}-\u{21FF}](?:️)?(?:‍[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}](?:️)?)*)/gu;

/** Twemoji's file name: code points in hex, dropping FE0F unless the emoji is a ZWJ sequence. */
export function codeFor(emoji) {
  const points = [...emoji].map((c) => c.codePointAt(0).toString(16));
  return (points.includes('200d') ? points : points.filter((p) => p !== 'fe0f')).join('-');
}

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(
    entries.map((e) => (e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)])),
  );
  return files.flat();
}

async function svgFor(code) {
  const cached = join(SVG_CACHE, `${code}.svg`);
  if (existsSync(cached)) return readFile(cached, 'utf8');
  const res = await fetch(`${TWEMOJI}/${code}.svg`);
  if (!res.ok) throw new Error(`No Twemoji for ${code} (${res.status})`);
  const svg = await res.text();
  await writeFile(cached, svg);
  return svg;
}

function render(svg, outlined) {
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  const box = 36 + PAD * 2;
  // Dilate the shape's alpha, soften the corners, fill it white, and draw the emoji on top.
  const filter = `<filter id="sticker" x="-30%" y="-30%" width="160%" height="160%">
    <feMorphology in="SourceAlpha" operator="dilate" radius="${OUTLINE}" result="grown"/>
    <feGaussianBlur in="grown" stdDeviation="0.45" result="soft"/>
    <feComponentTransfer in="soft" result="edge"><feFuncA type="linear" slope="3" intercept="-0.6"/></feComponentTransfer>
    <feFlood flood-color="#FFFFFF"/>
    <feComposite in2="edge" operator="in" result="white"/>
    <feMerge><feMergeNode in="white"/><feMergeNode in="SourceGraphic"/></feMerge>
  </filter>`;
  const wrapped = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${-PAD} ${-PAD} ${box} ${box}" width="${SIZE}" height="${SIZE}">
    <defs>${outlined ? filter : ''}</defs>
    <g${outlined ? ' filter="url(#sticker)"' : ''}>${inner}</g>
  </svg>`;
  return new Resvg(wrapped, { fitTo: { mode: 'width', value: SIZE } }).render().asPng();
}

async function main() {
  await mkdir(SVG_CACHE, { recursive: true });
  const files = (await walk(SRC)).filter((f) => /\.(ts|tsx)$/.test(f) && !f.includes('__tests__'));
  const found = new Set();
  for (const file of files) {
    if (file.endsWith('constants/icons.ts')) continue;
    for (const match of (await readFile(file, 'utf8')).matchAll(EMOJI)) {
      if (!SKIP.has(match[0])) found.add(match[0]);
    }
  }
  const byCode = new Map();
  for (const emoji of found) byCode.set(codeFor(emoji), emoji);

  const entries = [];
  for (const [code, emoji] of [...byCode].sort()) {
    const svg = await svgFor(code);
    await writeFile(join(OUT, `${code}.png`), render(svg, true));
    const plain = PLAIN.includes(emoji);
    if (plain) await writeFile(join(OUT, `${code}-plain.png`), render(svg, false));
    entries.push({ code, emoji, plain });
  }

  const lines = entries.map(
    ({ code, emoji, plain }) =>
      `  '${code}': { sticker: require('@/assets/icons/${code}.png')${
        plain ? `, plain: require('@/assets/icons/${code}-plain.png')` : ''
      } }, // ${emoji}`,
  );
  await writeFile(
    'src/constants/icons.ts',
    `// Generated by scripts/build-icons.mjs. Do not edit by hand.
// Twemoji graphics by Twitter, Inc. and contributors, CC-BY 4.0.

import type { ImageSource } from 'expo-image';

export type IconArt = { sticker: ImageSource; plain?: ImageSource };

/** Every emoji the app shows, keyed by Twemoji code (hex code points). */
export const ICONS: Record<string, IconArt> = {
${lines.join('\n')}
};
`,
  );
  console.log(`${entries.length} icons written to ${OUT}`);
}

main();
